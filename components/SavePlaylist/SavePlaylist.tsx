import React, { useState } from "react";
import Spotify from "spotify-web-api-js";

import { useAuth } from "components/UserContext/UserContext";
import LoginBanner from "components/LoginBanner/LoginBanner";
import { ArtistData, Link } from "types";
import { CassetteTape, CircleCheckBig } from "lucide-react";

interface SavePlaylistProps {
  artistData: ArtistData;
  songs: Link[];
}

const TRACKS_PER_REQUEST = 100;

const chunk = <T,>(items: T[], size: number): T[][] => {
  const chunks: T[][] = [];
  for (let i = 0; i < items.length; i += size) {
    chunks.push(items.slice(i, i + size));
  }
  return chunks;
};

const isUnauthorized = (e: unknown) =>
  typeof e === "object" && e !== null && "status" in e && e.status === 401;

const SavePlaylist = ({ artistData: { name }, songs }: SavePlaylistProps) => {
  const [loading, setLoading] = useState(false);
  const [done, setDone] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const { user, logout } = useAuth();
  const createPlaylist = () => {
    if (user) {
      setLoading(true);
      setError(null);
      const s = new Spotify();
      s.setAccessToken(user.accessToken);
      s.createPlaylist(user.user.id, {
        name: `${name} - GigPlayList`,
        description: "Playlist generated by https://gigplaylist.sirlisko.com/",
        public: true,
      })
        .then((playlist) =>
          chunk(
            songs.map((s) => s.uri),
            TRACKS_PER_REQUEST,
          ).reduce<Promise<unknown>>(
            (promise, uris) =>
              promise.then(() => s.addTracksToPlaylist(playlist.id, uris)),
            Promise.resolve(),
          ),
        )
        .then(() => setDone(true))
        .catch((e) => {
          if (isUnauthorized(e)) {
            logout?.();
          }
          setError(
            "Something went wrong creating your playlist. Please try again.",
          );
        })
        .finally(() => setLoading(false));
    }
  };

  return (
    <div className="text-center mb-8">
      {error && (
        <p role="alert" className="mb-4 text-sm text-red-300">
          {error}
        </p>
      )}
      {loading ? (
        <p className="m-12 text-lg font-medium flex items-center justify-center">
          <CassetteTape className="mr-1 animate-bounce" /> Generating your
          playlist...
        </p>
      ) : done ? (
        <p className="m-12 text-lg font-medium flex items-center justify-center">
          <CircleCheckBig className="mr-2" /> Playlist created!
        </p>
      ) : (
        <LoginBanner onCreatePlaylist={createPlaylist} showDesc />
      )}
    </div>
  );
};

export default SavePlaylist;
